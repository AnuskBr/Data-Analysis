import scipy.stats as stats
#ANOVA
'''
H0: There are no significant differences in Book Intro Chapter across different Allegiances.
H1: There are significant differences in Book Intro Chapter across different Allegiances.
'''
#clean the dataset
filtered_data = got_prep.dropna(subset=['Book Intro Chapter', 'Allegiances'])

# group by allegiances
grouped_data = [filtered_data[filtered_data['Allegiances'] == allegiance]['Book Intro Chapter']
                for allegiance in filtered_data['Allegiances'].unique()]

# Perform one-way ANOVA
f_stat, p_value = stats.f_oneway(*grouped_data)

# Display results
print("ANOVA Results:")
print(f"F-Statistic: {f_stat}")
print(f"P-Value: {p_value}")

# Interpret results
if p_value < 0.05:
    print("\nConclusion: Reject H₀. There are significant differences in Book Intro Chapter across different Allegiances.")
else:
    print("\nConclusion: Fail to reject H₀. There are no significant differences in Book Intro Chapter across different Allegiances.")

#PEARSON'S R TEST
'''
H0: There is no significant correlation between Book of Death and Gender.
H1: There is a significant correlation between Book of Death and Gender.

'''
# Clean dataset for analysis
filtered_data = got_prep.dropna(subset=['Book of Death', 'Gender'])

# Split data
book_of_death = filtered_data['Book of Death']
gender = filtered_data['Gender']

# Pearson's R
r, p_value = stats.pearsonr(book_of_death, gender)

# Display results
print("Pearson’s R Test:")
print(f"Correlation Coefficient (R): {r}")
print(f"P-Value: {p_value}")

# Interpret results
if p_value < 0.05:
    print("\nConclusion: Reject H0. There is a significant correlation between Book of Death and Gender.")
else:
    print("\nConclusion: Fail to reject H0. No significant correlation between Book of Death and Gender.")