#CHI-SQUARE test
'''
H0: Gender has no effect on Nobility.
H1: Gender has an effect on Nobility.
'''
from scipy.stats import chi2_contingency
# Define a function to perform Chi-square test
def chi_square_test(feature1, feature2, alpha=0.05):
    contingency_table = pd.crosstab(got_prep[feature1], got_prep[feature2])
    chi2, p, dof, expected = chi2_contingency(contingency_table)
    #return chi2, p
    print(f"{feature1} vs {feature2}:")
    print(f"Chi-square statistic: {chi2}")
    print(f"P-value: {p}")
    print(f"Degrees of freedom: {dof}")
    print(f"Expected frequencies:\n{expected}")

    # Interpret results
    if p < alpha:
        print("\nConclusion: Reject H0. There is an effect between gender and nobility.")
    else:
        print("\nConclusion: Fail to reject H0. There is no significant effect between gender and nobility.")

# Gender vs Nobility
